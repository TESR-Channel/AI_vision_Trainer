"""Regenerate edge-files.js from edge-runtime/ (run after editing any file there).

The web page embeds these files into the device zip, so they must stay
byte-identical to edge-runtime/ - this script is the only way to update them.
    python tools/build_edge_files.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "edge-runtime"
FILES = ["predict.py", "export.py", "requirements.txt", "README_DEPLOY.md", "START_HERE.md", "START_HERE_DATASET.md", "install_windows.bat",
         "install_linux.sh", "install_pi.sh", "install_jetson.sh", "build_trt.sh"]

out = ["/* GENERATED by tools/build_edge_files.py from edge-runtime/ - do not edit by hand. */",
       "window.TESR_EDGE_FILES = {"]
for name in FILES:
    text = (SRC / name).read_text(encoding="utf-8").replace("\r\n", "\n")
    out.append("  %s: %s," % (json.dumps(name), json.dumps(text, ensure_ascii=False)))
out.append("};")
(ROOT / "edge-files.js").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote edge-files.js (%d files)" % len(FILES))


# ---- CHANGELOG.md from version.js (single source of truth, strict JSON inside) ----
_src = (ROOT / "version.js").read_text(encoding="utf-8")
_app = json.loads(_src[_src.index("window.TESR_APP = ") + len("window.TESR_APP = "):_src.rindex("}") + 1])
_lines = ["# Changelog - %s" % _app["name"], "",
          "Current version: **v%s** (%s). Also shown on the web page (click the version badge)." % (_app["version"], _app["date"]),
          "Generated from `version.js` by `tools/build_edge_files.py` - edit version.js, not this file.", ""]
for h in _app["history"]:
    _lines += ["## v%s - %s" % (h["v"], h["date"]), ""] + ["- " + x for x in h["en"]] + [""] + ["- " + x for x in h["th"]] + [""]
(ROOT / "CHANGELOG.md").write_text("\n".join(_lines), encoding="utf-8")
print("wrote CHANGELOG.md (v%s)" % _app["version"])
